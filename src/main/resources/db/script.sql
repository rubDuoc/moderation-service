-- Base de datos: Oracle Autonomous Database (BDFullstack3)
-- Ejecutar DESPUES de los scripts de user-service y forum-service.
-- USUARIO_ID / ADMIN_ID referencian a user-service y CONTENIDO_ID
-- a los temas o comentarios de forum-service.
-- ============================================================

DROP TABLE MODERACIONES CASCADE CONSTRAINTS;
DROP TABLE REPORTES CASCADE CONSTRAINTS;

CREATE TABLE REPORTES (
    ID               NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_CONTENIDO   VARCHAR2(20 CHAR)  NOT NULL CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
    CONTENIDO_ID     NUMBER(19, 0)      NOT NULL,
    USUARIO_ID       NUMBER(19, 0)      NOT NULL,
    MOTIVO           VARCHAR2(300 CHAR) NOT NULL,
    EXTRACTO         VARCHAR2(500 CHAR) NOT NULL,
    ESTADO           VARCHAR2(20 CHAR)  NOT NULL CHECK (ESTADO IN ('PENDIENTE', 'RESUELTO', 'DESCARTADO')),
    FECHA_REPORTE    TIMESTAMP(9)       NOT NULL,
    FECHA_RESOLUCION TIMESTAMP(9)
);

CREATE TABLE MODERACIONES (
    ID             NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO_CONTENIDO VARCHAR2(20 CHAR)  NOT NULL CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
    CONTENIDO_ID   NUMBER(19, 0)      NOT NULL,
    ACCION         VARCHAR2(20 CHAR)  NOT NULL CHECK (ACCION IN ('BANEAR', 'DESBANEAR', 'DESCARTAR')),
    ADMIN_ID       NUMBER(19, 0)      NOT NULL,
    MOTIVO         VARCHAR2(300 CHAR),
    REPORTE_ID     NUMBER(19, 0),
    FECHA          TIMESTAMP(9)       NOT NULL,
    CONSTRAINT FK_MODERACION_REPORTE FOREIGN KEY (REPORTE_ID) REFERENCES REPORTES (ID) ON DELETE SET NULL
);

